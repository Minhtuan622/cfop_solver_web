// A run starts and ends in a cube shape, never passes through one in between,
// keeps every piece in its layer and leaves the corners and the edges with
// different permutation parity. Seven slices is the shortest such run; the
// search takes about twenty seconds.
import { SQ1_SOLVED, turnLayers, sliceState, wedgeKind } from "../client/src/lib/squareOneModel";
const FULL = 0xfff, TOP = 0x249, BOT = 0x492;
const rot = (m: number, a: number) => { a = ((a % 12) + 12) % 12; return ((m << a) | (m >>> (12 - a))) & FULL; };
const sliceM = (t: number, b: number): [number, number] => [(t & 0x3f) | ((b & 0x3f) << 6), ((t >> 6) & 0x3f) | (b & 0xfc0)];
const ok = (m: number) => (m & 0x820) === 0;
const key = (t: number, b: number) => t | (b << 12);
const dist = new Uint8Array(1 << 24).fill(255); let fr: number[] = [];
