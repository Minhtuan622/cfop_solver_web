for (const seq of seqs) { const { e, c } = effect(seq); if (sg(e) === sg(c)) continue; odd++; byCost.set(seq.length / 2, (byCost.get(seq.length / 2) || 0) + 1); if (e.slice(0, 4).every(x => x < 4) && c.slice(0, 4).every(x => x < 4)) { const k = e.join("") + "|" + c.join(""); if (!pp.has(k)) pp.set(k, seq); } }
const rows = [...pp.values()].map(run => `  [${run.join(", ")}],`).join("\n");
